# Updates Orcinus' own translation catalogs. Orcinus reuses Dolphin's catalogs (po/<lang>/dolphin.po);
# po-orcinus/ holds only the strings that Dolphin does not have. This script
#   1. extracts every translatable string of src/ (like src/Messages.sh, without tests and dev tools),
#   2. drops the strings that Dolphin's catalog already contains (po/de/dolphin.po holds all of them),
#   3. writes the rest to po-orcinus/orcinus.pot and merges it into po-orcinus/<lang>/orcinus.po.
# Strings that upstream added but KDE's l10n has not synced yet also land here; that is harmless,
# Orcinus' translation wins over Dolphin's while both exist.
#
# Usage (from anywhere): po-orcinus/update-catalogs.sh

set -euo pipefail

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

cd "${root}/src"
python3 "${root}/po-orcinus/extractrc.py" $(find . -name '*.ui' -o -name '*.rc' -o -name '*.kcfg' | sort) > "${work}/rc.cpp"
keywords=(-ki18n:1 -ki18nc:1c,2 -ki18np:1,2 -ki18ncp:1c,2,3 -kki18n:1 -kki18nc:1c,2 -kki18np:1,2
          -kki18ncp:1c,2,3 -kxi18n:1 -kxi18nc:1c,2 -kxi18np:1,2 -kxi18ncp:1c,2,3 -kkxi18n:1 -kkxi18nc:1c,2
          -kkxi18np:1,2 -kkxi18ncp:1c,2,3 -kI18N_NOOP:1 -kI18NC_NOOP:1c,2)
xgettext --from-code=UTF-8 -C --kde -ci18n "${keywords[@]}" --package-name=orcinus \
    -o "${work}/all.pot" \
    $(find . -name '*.cpp' ! -path '*/servicemenuinstaller/*' ! -path '*/tests/*' ! -path '*/devmcp/*' | sort) \
    "${work}/rc.cpp"

# Entries only in all.pot = Orcinus' own strings.
msgcomm --less-than=2 -o "${work}/unique.pot" "${work}/all.pot" "${root}/po/de/dolphin.po"
msgcomm --more-than=1 -o "${root}/po-orcinus/orcinus.pot" "${work}/all.pot" "${work}/unique.pot"
sed -i 's|^#: \./|#: src/|; s| \./| src/|g; s|^#: .*/rc\.cpp:[0-9]*$|#: (rc, kcfg or ui file)|' "${root}/po-orcinus/orcinus.pot"
# xgettext's placeholder header comments → the project's header (REUSE needs the SPDX lines).
sed -i '1,/^#, fuzzy$/{/^# /d; /^#$/d}' "${root}/po-orcinus/orcinus.pot"
spdx="SPDX"  # split, so REUSE does not read the tags below as this script's own
sed -i "1i # Template of Orcinus' own strings, generated by po-orcinus/update-catalogs.sh.\\n# ${spdx}-FileCopyrightText: 2026 Orcinus contributors\\n# ${spdx}-License-Identifier: GPL-2.0-or-later" "${root}/po-orcinus/orcinus.pot"
echo "$(grep -c '^msgid ' "${root}/po-orcinus/orcinus.pot") entries (incl. header) in po-orcinus/orcinus.pot"

for po in "${root}"/po-orcinus/*/orcinus.po; do
    msgmerge --quiet --update --backup=none --no-fuzzy-matching "${po}" "${root}/po-orcinus/orcinus.pot"
    echo "${po#"${root}/"}: $(msgfmt --statistics -o /dev/null "${po}" 2>&1)"
done
